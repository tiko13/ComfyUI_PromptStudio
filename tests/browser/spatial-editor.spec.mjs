import assert from 'node:assert/strict';
import {join} from 'node:path';
import AxeBuilder from '@axe-core/playwright';
import {startFixture} from './fixture.mjs';
import {mossCatalog, mossProfile} from '../moss-fixture.mjs';

const fixture = await startFixture();
const profile = await mossProfile(mossCatalog.find(p => p.id === 'moss_sft_controlled'));
try {
  const page = await fixture.newPage();
  await page.setViewportSize({width: 1920, height: 1080});
  await page.evaluate(async profile => {
    const {openSpatialEditor} = await import('/extensions/ComfyUI_PromptStudio/js/prompt-studio/ui/spatial-editor.js');
    window.openEditor = (value, aspect = 1) => openSpatialEditor({profile, value, aspect,
      save: value => {window.savedSpatial = value;}, defaults: {},
      upload: async () => ({filename: 'regions.png', subfolder: '', type: 'input', width: 1024, height: 1024}),
      imageUrl: () => 'data:image/svg+xml,' + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="300" height="300"><rect width="300" height="300" fill="#385677"/></svg>')});
    window.openEditor();
  }, profile);
  const dialog = page.getByRole('dialog', {name: 'Layout and control maps', exact: true});
  const button = name => dialog.getByRole('button', {name, exact: true});
  const canvas = dialog.locator('.ps-spatial-canvas');
  const boxes = dialog.locator('.ps-spatial-box');
  assert.ok((await dialog.boundingBox()).width > 1800, 'Editor uses the wide display');
  await button('Add character').click();
  const description = dialog.getByLabel('Description', {exact: true});
  const initialHeight = (await description.boundingBox()).height;
  assert.ok(initialHeight >= 160, 'Description starts with comfortable writing space');
  await description.fill(Array.from({length: 16}, (_, i) => `Line ${i + 1}: a person wearing a blue coat.`).join('\n'));
  assert.ok((await description.boundingBox()).height > initialHeight, 'Description grows with its contents');
  await description.evaluate(input => {window.descriptionNode = input; input.setSelectionRange(5, 5);});
  await description.press('Delete');
  assert.equal(await boxes.count(), 1, 'Delete in a textarea edits text, not segments');
  assert.equal(await description.evaluate(input => input === window.descriptionNode && document.activeElement === input && input.selectionStart === 5), true, 'Typing preserves the element, focus and caret');
  await description.fill('A person in a blue coat');
  await canvas.focus(); await page.keyboard.press('Control+d');
  assert.equal(await boxes.count(), 2);
  await page.keyboard.press('Delete'); assert.equal(await boxes.count(), 1);
  await page.keyboard.press('Control+z'); assert.equal(await boxes.count(), 2, 'Delete is undoable');
  await page.keyboard.press('Control+Shift+z'); assert.equal(await boxes.count(), 1);
  await button('Add text').click(); await dialog.getByLabel('Exact text', {exact: true}).fill('OPEN');
  await button('Send backward').click();
  assert.deepEqual(await dialog.locator('.ps-spatial-segment-name').allTextContents(), ['A person in a blue coat', 'OPEN'], 'List displays foreground first');
  // Selecting, zooming and panning must not add undo steps.
  await dialog.locator('.ps-spatial-segment').filter({hasText: 'A person in a blue coat'}).click();
  await button('Zoom in').click(); await button('Fit canvas').click();
  await button('Undo').click();
  assert.deepEqual(await dialog.locator('.ps-spatial-segment-name').allTextContents(), ['OPEN', 'A person in a blue coat']);
  await button('Redo').click();
  const rows = dialog.locator('.ps-spatial-segment');
  await rows.nth(0).dragTo(rows.nth(1));
  assert.deepEqual(await dialog.locator('.ps-spatial-segment-name').allTextContents(), ['OPEN', 'A person in a blue coat'], 'Dragging rows changes stacking order');
  await button('Undo').click();
  await button('Select').click();
  let rect = await canvas.boundingBox();
  await page.mouse.click(rect.x + rect.width * .85, rect.y + rect.height * .85);
  assert.equal(await boxes.count(), 2, 'Clicking empty canvas never creates a segment');
  assert.equal(await dialog.locator('.ps-spatial-box.selected').count(), 0);
  await button('Draw').click();
  await page.mouse.click(rect.x + rect.width * .8, rect.y + rect.height * .8);
  assert.equal(await boxes.count(), 2, 'Drawing requires a meaningful drag');
  await page.mouse.move(rect.x + rect.width * .55, rect.y + rect.height * .55); await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .85, rect.y + rect.height * .85, {steps: 5}); await page.mouse.up();
  assert.equal(await boxes.count(), 3);
  await dialog.getByLabel('Description', {exact: true}).fill('A wooden table with a vase');
  const selected = dialog.locator('.ps-spatial-box.selected');
  const original = await selected.boundingBox();
  const handle = await selected.locator('[data-edge=nw]').boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2); await page.mouse.down();
  await page.mouse.move(handle.x - 30, handle.y - 30, {steps: 5}); await page.mouse.up();
  assert.ok((await selected.boundingBox()).width > original.width + 20, 'Northwest handle resizes from that corner');
  await button('Undo').click();
  assert.ok(Math.abs((await selected.boundingBox()).width - original.width) < 1, 'A complete resize is one undo step');
  await button('Select').click();
  const beforeCancel = await selected.evaluate(box => box.style.cssText);
  const moveBox = await selected.boundingBox();
  await page.mouse.move(moveBox.x + 20, moveBox.y + 20); await page.mouse.down();
  await page.mouse.move(moveBox.x + 50, moveBox.y + 50);
  await page.keyboard.press('Escape'); await page.mouse.up();
  assert.equal(await selected.evaluate(box => box.style.cssText), beforeCancel, 'Escape cancels a gesture without closing the editor');
  await button('Add color').click();
  await dialog.getByLabel('Hex 1', {exact: true}).fill('#336699'); await dialog.getByLabel('Hex 1', {exact: true}).press('Tab');
  assert.equal(await dialog.getByLabel('Color 1', {exact: true}).inputValue(), '#336699');
  const xInput = dialog.getByLabel('x (%)', {exact: true});
  await xInput.fill('40');
  await button('Duplicate').click();
  assert.equal(await boxes.count(), 4, 'Editing a coordinate does not swallow the next button click');
  await canvas.focus(); await page.keyboard.press('Delete');
  assert.equal(await boxes.count(), 3);
  await button('Pan').click();
  const panRect = await canvas.boundingBox();
  await page.mouse.move(panRect.x + 40, panRect.y + 40); await page.mouse.down();
  await page.mouse.move(panRect.x + 90, panRect.y + 60); await page.mouse.up();
  assert.ok((await canvas.boundingBox()).x > panRect.x + 40, 'Pan moves the view');
  await button('Fit canvas').click();
  assert.ok(Math.abs((await canvas.boundingBox()).x - panRect.x) < 1, 'Fit resets pan');
  await button('Select').click();
  await dialog.getByRole('separator', {name: 'Resize properties panel'}).focus();
  const inspectorWidth = (await dialog.locator('.ps-spatial-inspector').boundingBox()).width;
  await page.keyboard.press('ArrowLeft');
  assert.ok((await dialog.locator('.ps-spatial-inspector').boundingBox()).width > inspectorWidth);
  if (process.env.SPATIAL_SCREENSHOTS) await page.screenshot({path: join(process.env.SPATIAL_SCREENSHOTS, 'spatial-desktop.png')});
  await dialog.getByRole('tab', {name: 'Control maps', exact: true}).click();
  await dialog.locator('.ps-spatial-map-row').filter({hasText: 'color map'}).click();
  await button('Create color map from layout').click();
  await dialog.getByLabel('Use color map', {exact: true}).waitFor();
  await page.waitForFunction(() => !document.querySelector('.ps-spatial-workspace').inert);
  await dialog.getByRole('tab', {name: 'Layout', exact: true}).click();
  await canvas.focus(); await page.keyboard.press('ArrowRight');
  await dialog.getByRole('tab', {name: 'Control maps', exact: true}).click();
  assert.match(await dialog.locator('.ps-spatial-warning').innerText(), /Layout changed/);
  await button('Apply changes').click(); await dialog.waitFor({state: 'detached'});
  assert.ok(await page.evaluate(() => window.savedSpatial.guides.color.layoutSignature), 'Generated-map provenance survives normalization');
  await page.evaluate(() => window.openEditor(window.savedSpatial));
  await dialog.getByRole('tab', {name: 'Control maps', exact: true}).click();
  await dialog.locator('.ps-spatial-map-row').filter({hasText: 'color map'}).click();
  assert.equal(await dialog.locator('.ps-spatial-warning').count(), 1, 'Stale-map warning survives reopen');
  const audit = await new AxeBuilder({page}).include('.ps-spatial-editor').analyze();
  assert.deepEqual(audit.violations.map(v => ({id: v.id, help: v.help})), []);
  await dialog.getByRole('tab', {name: 'Layout', exact: true}).click();
  await page.setViewportSize({width: 1100, height: 800});
  await dialog.locator('.ps-spatial-segments').waitFor({state: 'hidden'});
  await button('Segments').click(); await dialog.locator('.ps-spatial-segments').waitFor({state: 'visible'});
  await button('Segments').click(); await dialog.locator('.ps-spatial-segments').waitFor({state: 'hidden'});
  await page.setViewportSize({width: 390, height: 844});
  await button('Properties').click(); await dialog.locator('.ps-spatial-inspector').waitFor({state: 'visible'});
  assert.ok((await dialog.locator('.ps-spatial-inspector').boundingBox()).width <= 390);
  if (process.env.SPATIAL_SCREENSHOTS) await page.screenshot({path: join(process.env.SPATIAL_SCREENSHOTS, 'spatial-mobile.png')});
  await button('Properties').click();
  rect = await canvas.boundingBox(); assert.ok(rect.x >= 0 && rect.x + rect.width <= 390);
  assert.equal(await dialog.evaluate(d => d.scrollWidth <= d.clientWidth), true, 'No horizontal overflow on mobile');
  await button('Cancel').click();
  await page.setViewportSize({width: 1440, height: 900});
  await page.evaluate(() => window.openEditor(window.savedSpatial, 9 / 16));
  rect = await canvas.boundingBox();
  const viewport = await dialog.locator('.ps-spatial-viewport').boundingBox();
  assert.ok(rect.height <= viewport.height && rect.width <= viewport.width, 'Portrait canvas fits both dimensions');
  assert.ok(Math.abs(rect.width / rect.height - 9 / 16) < .01);
  await button('Draw').click();
  const countBeforeOverlap = await boxes.count();
  await page.mouse.move(rect.x + rect.width * .15, rect.y + rect.height * .15); await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .3, rect.y + rect.height * .25, {steps: 4}); await page.mouse.up();
  assert.equal(await boxes.count(), countBeforeOverlap + 1, 'Draw can create a new segment inside an existing box');
  await button('Undo').click(); assert.equal(await boxes.count(), countBeforeOverlap);
  await button('Cancel').click();
  assert.deepEqual(fixture.errors, []);
  console.log('Spatial workspace: adaptive text, focus, Delete, duplication, undo, drawing, resize, gesture cancel, palette, maps, persisted warnings, panels, accessibility and portrait/mobile passed.');
} finally {await fixture.close();}
