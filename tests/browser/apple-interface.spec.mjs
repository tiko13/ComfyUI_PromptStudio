import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
import {startFixture,attachVideo,videoEnabled,root} from './fixture.mjs';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
const fixture=await startFixture({contextOptions:{hasTouch:true}});
try {
 const page=await fixture.newPage();
 await mkdir(resolve(root,'test-results/browser'),{recursive:true});
 const cdp=await fixture.context.newCDPSession(page);
 const shot=name=>page.screenshot({path:resolve(root,`test-results/browser/apple-${name}.png`)});
 const audit=async selector=>{
   const result=await new AxeBuilder({page}).include(selector).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
   assert.deepEqual(result.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
 };
 const fit=async selector=>{
   const r=await page.locator(selector).boundingBox(),v=page.viewportSize();
   assert.ok(r&&r.x>=-1&&r.y>=-1&&r.x+r.width<=v.width+1&&r.y+r.height<=v.height+1,`${selector}: ${JSON.stringify(r)}`);
 };
 const swipe=async(selector,dx,cancel=false)=>{
   const r=await page.locator(selector).boundingBox(),x=r.x+r.width/2,y=r.y+r.height/2;
   await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y,id:0}]});
   for(const f of [.3,.6,1])await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+dx*f,y,id:0}]});
   await cdp.send('Input.dispatchTouchEvent',{type:cancel?'touchCancel':'touchEnd',touchPoints:[]});
 };
 await page.setViewportSize({width:390,height:844});
 const options=page.locator('.promptstudio-compose-options');
 await page.waitForFunction(()=>!document.querySelector('.promptstudio-compose-options').open);
 await page.locator('#promptstudio-revision').fill('Preserve my mobile draft');
 await options.locator('summary').tap();
 await page.locator('#promptstudio-auto-generate').uncheck();
 await options.locator('summary').tap();
 assert.equal(await page.locator('#promptstudio-auto-generate').isChecked(),false);
 await page.locator('#promptstudio-mobile-toggle-inspector').tap();
 await page.waitForFunction(()=>document.querySelector('.promptstudio-main').inert);
 assert.equal(await page.getByRole('dialog',{name:'Controls',exact:true}).count(),1);
 await audit('.promptstudio-inspector');
 await swipe('.promptstudio-controls-title',35,true);
 assert.equal(await page.getByRole('dialog',{name:'Controls',exact:true}).count(),1,'Cancelled header drag preserves the drawer');
 await swipe('.promptstudio-controls-title',160);
 await page.waitForFunction(()=>!document.querySelector('.promptstudio-main').inert);
 assert.equal(await page.locator('#promptstudio-mobile-toggle-inspector').evaluate(n=>n===document.activeElement),true);
 await page.locator('#promptstudio-mobile-toggle-inspector').tap();
 await page.locator('#promptstudio-toggle-studio-settings').tap();
 await page.locator('#promptstudio-open-backend-settings').tap();
 const profileHeight=await page.locator('.promptstudio-llm-profile-field').evaluate(n=>n.getBoundingClientRect().height);
 assert.ok(profileHeight<90,'Profile selector must not retain its desktop flex basis as vertical blank space');
 await audit('#promptstudio-backend-settings-dialog');
 await page.keyboard.press('Escape');await page.keyboard.press('Escape');await page.locator('#promptstudio-close-inspector').tap();
 assert.equal(await page.locator('#promptstudio-revision').inputValue(),'Preserve my mobile draft');
 await shot('image-phone');
 const header=page.locator('.promptstudio-mobile-header');
 assert.match(await header.evaluate(n=>getComputedStyle(n).backdropFilter),/blur/);
 await cdp.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-transparency',value:'reduce'}]});
 assert.equal(await page.evaluate(()=>matchMedia('(prefers-reduced-transparency: reduce)').matches),true);
 assert.equal(await header.evaluate(n=>getComputedStyle(n).backdropFilter),'none');
 await cdp.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-contrast',value:'more'}]});
 assert.equal(await header.evaluate(n=>getComputedStyle(n).backdropFilter),'none');
 await shot('high-contrast');
 await cdp.send('Emulation.setEmulatedMedia',{features:[]});
 await page.evaluate(()=>document.documentElement.style.fontSize='24px');
 await fit('.promptstudio-mobile-header');await fit('#promptstudio-send');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await shot('large-text');
 await page.evaluate(()=>document.documentElement.style.removeProperty('font-size'));
 if(videoEnabled){
   await attachVideo(page);await page.locator('#psvstudio-mobile-projects').tap();await page.locator('#psvstudio-new-project').tap();
   if(await page.locator('#psvstudio-close-projects').isVisible())await page.locator('#psvstudio-close-projects').tap();
   await page.locator('#psvstudio-project-title').fill('Touch workspace');
   const tools=page.locator('.psvstudio-tools-menu');
   assert.equal(await tools.evaluate(n=>n.open),false);
   assert.equal(await page.locator('#psvstudio-workflow').isVisible(),true);
   await tools.locator(':scope > summary').tap();await fit('#psvstudio-reset');await shot('video-tools');
   await page.keyboard.press('Escape');assert.equal(await tools.evaluate(n=>n.open),false);
   await page.locator('#psvstudio-mobile-inspector').tap();
   await page.waitForFunction(()=>document.querySelector('.psvstudio-main').inert);
   assert.equal(await page.locator('.psvstudio-adapters').evaluate(n=>n.open),false);
   await audit('.psvstudio-inspector');await shot('video-shots');
   await swipe('#psvstudio-inspector-title',160);await page.waitForFunction(()=>!document.querySelector('.psvstudio-main').inert);
   await page.getByRole('button',{name:'Global settings',exact:true}).tap();
   await audit('.psvstudio-global-settings-dialog');await shot('video-settings');await page.keyboard.press('Escape');
   await page.locator('#psvstudio-mobile-inspector').tap();await page.getByRole('button',{name:'Edit shot',exact:true}).tap();
   await page.setViewportSize({width:390,height:480});await fit('.psvstudio-shot-editor-footer');await shot('shot-keyboard');await page.keyboard.press('Escape');
   await page.locator('#psvstudio-close-inspector').tap();
   await page.setViewportSize({width:1600,height:1000});await fit('.psvstudio-topbar');await fit('.psvstudio-inspector');
   assert.equal(await page.locator('#psvstudio-project-title').inputValue(),'Touch workspace');await shot('video-tablet');
 }
 assert.deepEqual(fixture.errors,[]);
 console.log('Apple interface: drawer isolation/gestures/focus, preserved drafts, Options/Tools, form spacing, large text, opaque accessibility fallbacks and both studios passed.');
}finally{await fixture.close();}
